-- name: db-engine-ci-specs
SELECT s.CLASSIFICATIONID AS CI_CLASS,
    c.ASSETATTRID,
    c.SECTION,
    a.DATATYPE,
    a.MEASUREUNITID AS ATTR_UNIT,
    c.MEASUREUNITID AS SPEC_UNIT,
    a.DOMAINID,
    u.MANDATORY,
    u.USEINSPEC
FROM MAXIMO.CLASSSTRUCTURE s
JOIN MAXIMO.CLASSSPEC c ON c.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
JOIN MAXIMO.ASSETATTRIBUTE a
    ON a.ASSETATTRIBUTEID = c.ASSETATTRIBUTEID
   AND a.ASSETATTRID = c.ASSETATTRID
LEFT JOIN MAXIMO.CLASSSPECUSEWITH u
    ON u.CLASSSPECID = c.CLASSSPECID AND u.OBJECTNAME = 'CI'
WHERE s.CLASSIFICATIONID IN (
    'CI.DATABASESERVER',
    'CI.SQLSERVER',
    'CI.DB2INSTANCE',
    'CI.ORACLEINSTANCE'
)
ORDER BY s.CLASSIFICATIONID, c.ASSETATTRID;

-- name: db-engine-spec-union
SELECT u.ASSETATTRID,
    MAX(CASE WHEN u.CI_CLASS = 'CI.DATABASESERVER' THEN 1 ELSE 0 END) AS CI_DBSERVER,
    MAX(CASE WHEN u.CI_CLASS = 'CI.SQLSERVER' THEN 1 ELSE 0 END) AS CI_SQLSERVER,
    MAX(CASE WHEN u.CI_CLASS = 'CI.DB2INSTANCE' THEN 1 ELSE 0 END) AS CI_DB2INSTANCE,
    MAX(CASE WHEN u.CI_CLASS = 'CI.ORACLEINSTANCE' THEN 1 ELSE 0 END) AS CI_ORACLEINSTANCE,
    MAX(u.DATATYPE) AS DATATYPE,
    MAX(CASE WHEN u.ACTCI_CLASS = 'APP.DB.GENERICDATABASESERVER' THEN 1 ELSE 0 END) AS ACT_GENERIC,
    MAX(CASE WHEN u.ACTCI_CLASS = 'APP.DB.DATABASESERVER' THEN 1 ELSE 0 END) AS ACT_DBSERVER,
    MAX(CASE WHEN u.ACTCI_CLASS = 'APP.DB.MSSQL.SQLSERVER' THEN 1 ELSE 0 END) AS ACT_SQLSERVER,
    MAX(CASE WHEN u.ACTCI_CLASS = 'APP.DB.DB2.DB2INSTANCE' THEN 1 ELSE 0 END) AS ACT_DB2INSTANCE,
    MAX(CASE WHEN u.ACTCI_CLASS = 'APP.DB.ORACLE.ORACLEINSTANCE' THEN 1 ELSE 0 END) AS ACT_ORACLEINSTANCE
FROM (
    SELECT s.CLASSIFICATIONID AS CI_CLASS,
        CAST(NULL AS VARCHAR(60)) AS ACTCI_CLASS,
        c.ASSETATTRID,
        a.DATATYPE
    FROM MAXIMO.CLASSSTRUCTURE s
    JOIN MAXIMO.CLASSSPEC c ON c.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
    JOIN MAXIMO.ASSETATTRIBUTE a
        ON a.ASSETATTRIBUTEID = c.ASSETATTRIBUTEID
       AND a.ASSETATTRID = c.ASSETATTRID
    WHERE s.CLASSIFICATIONID IN (
        'CI.DATABASESERVER', 'CI.SQLSERVER', 'CI.DB2INSTANCE', 'CI.ORACLEINSTANCE'
    )
    UNION ALL
    SELECT CAST(NULL AS VARCHAR(60)) AS CI_CLASS,
        s.CLASSIFICATIONID AS ACTCI_CLASS,
        c.ASSETATTRID,
        a.DATATYPE
    FROM MAXIMO.CLASSSTRUCTURE s
    JOIN MAXIMO.CLASSSPEC c ON c.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
    JOIN MAXIMO.ASSETATTRIBUTE a
        ON a.ASSETATTRIBUTEID = c.ASSETATTRIBUTEID
       AND a.ASSETATTRID = c.ASSETATTRID
    WHERE s.CLASSIFICATIONID IN (
        'APP.DB.GENERICDATABASESERVER', 'APP.DB.DATABASESERVER',
        'APP.DB.MSSQL.SQLSERVER', 'APP.DB.DB2.DB2INSTANCE', 'APP.DB.ORACLE.ORACLEINSTANCE'
    )
) u
GROUP BY u.ASSETATTRID
ORDER BY u.ASSETATTRID;

