    'APP.APPLICATION', 'APP.DB.DATABASESERVER', 'APP.WEB.WEBSERVER',
    'APP.APPSERVER', 'APP.GENERICAPPSERVER', 'APP.J2EE.J2EESERVER',
    'APP.J2EE.J2EEAPPLICATION',
