-- DB Instance, Application Component, Device의 분류·승격·관계 후보를 확인한다.
-- 블록 설명은 이 머리말에만 적는다. 블록 사이 주석은 앞 블록 SQL 뒤에 붙는다.
--
-- db-engine-ci-specs            승격 대상 CI 분류가 제공하는 속성 템플릿. ACTCI 수집 속성의 대조 기준.
-- db-engine-spec-union          CI 4개 분류의 속성 합집합과 ACTCI 보유 여부를 한 행에서 대조.
-- db-engine-device-rule-flags   db-engine-device-rules 에 REVRELATIONSHIP·SWAPPED 를 더한 설정 원문.
-- db-instance-database-rules    Instance -> Database 분류쌍 규칙. 0건이면 등록 전까지 적재 불가.

-- name: db-app-actci-classes
SELECT s.CLASSIFICATIONID,
    s.CLASSSTRUCTUREID,
    s.PARENT,
    s.DESCRIPTION,
    (SELECT COUNT(*) FROM MAXIMO.CLASSSPEC c
      WHERE c.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID) AS SPEC_COUNT,
    (SELECT COUNT(*) FROM MAXIMO.CLASSSPECUSEWITH u
      WHERE u.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
        AND u.OBJECTNAME = 'ACTCI' AND u.USEINSPEC = 1) AS ACTCI_SPEC_COUNT
FROM MAXIMO.CLASSSTRUCTURE s
WHERE EXISTS (
    SELECT 1 FROM MAXIMO.CLASSUSEWITH w
    WHERE w.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
      AND w.OBJECTNAME = 'ACTCI'
)
AND (
    s.CLASSIFICATIONID LIKE 'APP.%'
    OR UPPER(s.CLASSIFICATIONID) LIKE '%APPLICATION%'
    OR UPPER(s.CLASSIFICATIONID) LIKE '%DATABASE%'
    OR UPPER(s.CLASSIFICATIONID) LIKE '%WEB%SERVER%'
)
ORDER BY s.CLASSIFICATIONID;

-- name: db-app-selected-specs
SELECT s.CLASSIFICATIONID,
    c.ASSETATTRID,
    a.DESCRIPTION,
    a.DATATYPE,
    c.SECTION,
    u.SEQUENCE,
    u.MANDATORY,
    u.USEINSPEC
FROM MAXIMO.CLASSSTRUCTURE s
JOIN MAXIMO.CLASSSPEC c ON c.CLASSSTRUCTUREID = s.CLASSSTRUCTUREID
LEFT JOIN MAXIMO.ASSETATTRIBUTE a
  ON a.ASSETATTRIBUTEID = c.ASSETATTRIBUTEID
 AND a.ASSETATTRID = c.ASSETATTRID
LEFT JOIN MAXIMO.CLASSSPECUSEWITH u
  ON u.CLASSSPECID = c.CLASSSPECID
 AND u.OBJECTNAME = 'ACTCI'
WHERE s.CLASSIFICATIONID IN (
    'APP.APPLICATION',
    'APP.DB.DATABASESERVER',
    'APP.WEB.WEBSERVER',
    'APP.APPSERVER',
    'APP.GENERICAPPSERVER',
    'APP.J2EE.J2EESERVER',
    'APP.J2EE.J2EEAPPLICATION'
)
ORDER BY s.CLASSIFICATIONID, c.ASSETATTRID;

