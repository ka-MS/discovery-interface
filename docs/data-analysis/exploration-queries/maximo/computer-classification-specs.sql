'NET.IPNETWORK',
'APP.SOFTWAREIMAGE',
'APP.SOFTWAREMODULE',
'CI.COMPUTERSYSTEM',
'CI.VIRTUALCOMPUTERSYSTEM',
'GENCSYS',
'ZCSYS',
