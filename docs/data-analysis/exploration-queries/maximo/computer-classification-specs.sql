-- name: selected-classes
SELECT S.CLASSIFICATIONID,S.CLASSSTRUCTUREID,P.CLASSIFICATIONID AS PARENT_NAME,U.OBJECTNAME,U.TOPLEVEL,U.AUTOCREATECI
FROM MAXIMO.CLASSSTRUCTURE S
LEFT JOIN MAXIMO.CLASSSTRUCTURE P ON P.CLASSSTRUCTUREID=S.PARENT
LEFT JOIN MAXIMO.CLASSUSEWITH U ON U.CLASSSTRUCTUREID=S.CLASSSTRUCTUREID
WHERE S.CLASSIFICATIONID IN ('SYS.COMPUTERSYSTEM',
'SYS.UNITARYCOMPUTERSYSTEM',
'SYS.VIRTUALCOMPUTERSYSTEM',
'SYS.GENERICCOMPUTERSYSTEM',
'SYS.CPU',
