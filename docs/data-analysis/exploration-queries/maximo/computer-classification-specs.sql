-- name: selected-specs
SELECT S.CLASSIFICATIONID,C.CLASSSPECID,C.ASSETATTRID,C.ASSETATTRIBUTEID,
A.ASSETATTRID AS MATCHED_ATTRID,A.DESCRIPTION,A.DATATYPE,
C.SECTION,C.MEASUREUNITID,A.MEASUREUNITID AS ATTRIBUTE_UNIT,
C.DOMAINID,C.INHERITEDFROMID,C.APPLYDOWNHIER,
U.OBJECTNAME,U.MANDATORY,U.SEQUENCE,U.USEINSPEC,U.DEFAULTALNVALUE,U.DEFAULTNUMVALUE,
N.DATATYPE AS NAME_MATCH_TYPE
FROM MAXIMO.CLASSSTRUCTURE S
JOIN MAXIMO.CLASSSPEC C ON C.CLASSSTRUCTUREID=S.CLASSSTRUCTUREID
LEFT JOIN MAXIMO.ASSETATTRIBUTE A ON A.ASSETATTRIBUTEID=C.ASSETATTRIBUTEID AND A.ASSETATTRID=C.ASSETATTRID
LEFT JOIN MAXIMO.ASSETATTRIBUTE N ON N.ASSETATTRID=C.ASSETATTRID
LEFT JOIN MAXIMO.CLASSSPECUSEWITH U ON U.CLASSSPECID=C.CLASSSPECID
